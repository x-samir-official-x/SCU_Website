/** يحوّل الأرقام الهندية (٠١٢…) إلى لاتينية ويحذف المسافات والفواصل. */
export function normalizeDigits(value: unknown): string {
  return String(value ?? '')
    .replace(/[٠-٩]/g, (d) => String(d.charCodeAt(0) - 0x660))
    .replace(/[۰-۹]/g, (d) => String(d.charCodeAt(0) - 0x6f0))
    .replace(/[\s,\-_.]/g, '');
}
